//! `agentcenter-cli gen-docs <markdown|man>`: the CLI reference and the man page,
//! rendered from `cmd::COMMANDS` so they cannot drift from the code.

use crate::cmd::{COMMANDS, usage};

const INTRO: &str = "Headless AgentCenter: a snapshot of AI coding sessions as a table or JSON.";

pub fn run(args: Vec<String>) -> Result<(), String> {
    let text = match args.as_slice() {
        [f] if f == "markdown" => markdown(),
        [f] if f == "man" => man(),
        _ => return Err("gen-docs: expected one format, `markdown` or `man`".into()),
    };
    print!("{text}");
    Ok(())
}

pub fn markdown() -> String {
    let mut s = String::new();
    s.push_str("<!-- Generated by scripts/gen-docs.sh from the code. Do not edit. -->\n\n");
    s.push_str(&format!(
        "# agentcenter-cli {}\n\n{INTRO}\n\n",
        env!("CARGO_PKG_VERSION")
    ));
    s.push_str(&format!("```text\n{}\n```\n\n", usage()));
    for c in COMMANDS {
        s.push_str(&format!(
            "## {}\n\n{}\n\n```text\n{}\n```\n\n",
            c.name, c.summary, c.help
        ));
    }
    s
}

/// Escape one line of text for roff: backslash, hyphen (so `--json` can be
/// copied from the rendered page) and a leading `.` or `'`.
fn roff(line: &str) -> String {
    let e = line.replace('\\', "\\e").replace('-', "\\-");
    if e.starts_with('.') || e.starts_with('\'') {
        format!("\\&{e}")
    } else {
        e
    }
}

pub fn man() -> String {
    let mut s = String::new();
    s.push_str(".\\\" Generated by scripts/gen-docs.sh from the code. Do not edit.\n");
    s.push_str(&format!(
        ".TH AGENTCENTER\\-CLI 1 \"\" \"agentcenter\\-cli {}\" \"User Commands\"\n",
        env!("CARGO_PKG_VERSION")
    ));
    s.push_str(&format!(
        ".SH NAME\nagentcenter\\-cli \\- {}\n.SH SYNOPSIS\n.B agentcenter\\-cli\n<command> [options]\n.SH DESCRIPTION\n{}\n",
        roff("AI coding sessions without the GUI"),
        roff(INTRO)
    ));
    s.push_str(".SH COMMANDS\n");
    for c in COMMANDS {
        s.push_str(&format!(".SS {}\n{}\n.PP\n.nf\n", c.name, roff(c.summary)));
        for line in c.help.lines() {
            s.push_str(&roff(line));
            s.push('\n');
        }
        s.push_str(".fi\n");
    }
    s
}
